import json


def schedule_parse(raw_data: list) -> str:
    raw_data_json = json.dumps(raw_data, ensure_ascii=False)

    prompt = f"""
Ты получаешь необработанные данные листа Excel с расписанием занятий в виде списка списков (raw_data).
Каждый вложенный список — это одна строка таблицы, элементы которой — значения ячеек по столбцам.
Разметка таблицы может быть неидеальной (объединённые ячейки, пустые значения, лишние пробелы, значения None).

Твоя задача — разобрать эти данные и вернуть расписание на неделю строго в формате JSON,
эквивалентном списку объектов Python dataclass:

class Lesson:
    cabinet: str | None
    lesson: str | None
    time: str | None

class DaySchedule:
    weekday: str
    lessons: list[Lesson]

Правила:
1. Названия дней недели должны быть только из набора: "пн", "вт", "ср", "чт", "пт", "сб", "вс" (нижний регистр, сокращённо).
2. Один элемент верхнего уровня — один день. Не создавай два объекта для одного и того же дня.
3. lessons — список уроков этого дня по порядку, в котором они идут в расписании.
4. Для каждого урока заполняй поля time (время урока), lesson (название предмета/занятия), cabinet (номер кабинета).
5. Если значение отсутствует, пустое или является техническим прочерком — используй строку "-".
6. Убирай лишние пробелы и неразрывные пробелы (\\xa0) из значений.
7. Не добавляй дни или уроки, которых нет в исходных данных, и не придумывай данные.
8. Ответ должен быть ТОЛЬКО валидным JSON-массивом объектов вида:
[
  {{
    "weekday": "пн",
    "lessons": [
      {{"cabinet": "101", "lesson": "Математика", "time": "08:30-09:15"}}
    ]
  }}
]
Без пояснений, без markdown-разметки (без ```), без каких-либо символов до или после JSON.

Вот исходные данные (raw_data):
{raw_data_json}
"""
    return prompt
