def welcome_content(name: str) -> Text:
    emoji_id, fallback = SCHOOL_EMOJI["school_building_small"]
    return Text(
        CustomEmoji(fallback, custom_emoji_id=emoji_id),
        f" Привет, {name}!\n\n",
        "Я показываю расписание уроков.\n\n",
        "/today — расписание на сегодня\n"
        "/tomorrow — расписание на завтра\n"
        "/week — расписание на всю неделю\n"
        "/profile — твой профиль\n"
        "/change_grade — сменить класс\n"
        "/change_schedule — сменить таблицу\n\n",
        "Загляни в меню снизу 👇",
    )


